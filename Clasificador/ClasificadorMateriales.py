import tensorflow as tf
from tensorflow.keras import layers, models

# 1. Cargamos la herramienta de preprocesamiento específica de MobileNetV2
# Esto escala los píxeles de las fotos automáticamente al formato que el modelo espera
preprocesamiento = tf.keras.applications.mobilenet_v2.preprocess_input

# 2. Descargamos el modelo base MobileNetV2 entrenado con el dataset gigante 'imagenet'
# Le decimos 'include_top=False' para quitarle su clasificador de fábrica y poner el nuestro
modelo_base = tf.keras.applications.MobileNetV2(
    input_shape=(224, 224, 3),
    include_top=False,
    weights='imagenet'
)

# 3. ¡CRUCIAL! Congelamos el modelo base para que no borre lo que ya sabe de fábrica
modelo_base.trainable = False

# 4. Construimos la estructura definitiva uniendo las piezas como un Lego
entradas = tf.keras.Input(shape=(224, 224, 3))
x = preprocesamiento(entradas)
x = modelo_base(x, training=False) # Corre en modo inferencia
x = layers.GlobalAveragePooling2D()(x) # Aplana la información de la imagen
x = layers.Dropout(0.2)(x) # Apaga neuronas al azar para que no se estudie las fotos de memoria
salidas = layers.Dense(6, activation='softmax')(x) # 6 salidas con probabilidad para nuestras 6 clases

modelo_final = models.Model(entradas, salidas)

# 5. Compilamos el modelo indicando cómo medir los errores y qué optimizador usar
modelo_final.compile(
    optimizer='adam',
    loss=tf.keras.losses.SparseCategoricalCrossentropy(),
    metrics=['accuracy']
)

# Mostramos el mapa de la estructura en pantalla
modelo_final.summary()
print("\n¡Estructura de la Inteligencia Artificial creada con éxito!")

