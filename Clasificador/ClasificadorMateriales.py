preprocesamiento = tf.keras.applications.mobilenet_v2.preprocess_input
modelo_base = tf.keras.applications.MobileNetV2(input_shape=(224, 224, 3), include_top=False, weights='imagenet')
modelo_base.trainable = False

# 5. Armamos el cerebro uniendo las piezas (¡ACÁ ESTÁ EL ERROR CORREGIDO!)
entradas = tf.keras.Input(shape=(224, 224, 3))
